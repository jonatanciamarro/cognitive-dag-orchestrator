    # ── Alert System ────────────────────────────────────────

    def _emit_alert(
        self,
        severity: AlertSeverity,
        source: str,
        message: str,
        context: dict[str, Any] | None = None,
    ) -> KernelAlert:
        """Internal alert emission."""
        alert = KernelAlert(
            severity=severity,
            source=source,
            message=message,
            context=context or {},
        )
        self._alerts.append(alert)

        # Keep alerts bounded
        if len(self._alerts) > 1000:
            self._alerts = self._alerts[-500:]

        return alert

    def acknowledge_alert(self, alert_id: str) -> bool:
        """Mark an alert as acknowledged."""
        for alert in self._alerts:
            if alert.alert_id == alert_id:
                alert.acknowledged = True
                return True
        return False

    def clear_alerts(self, severity: AlertSeverity | None = None) -> int:
        """Clear alerts, optionally filtered by severity."""
        before = len(self._alerts)
        if severity:
            self._alerts = [a for a in self._alerts if a.severity != severity]
        else:
            self._alerts = []
        return before - len(self._alerts)

    # ── Utility ─────────────────────────────────────────────

    def subsystem_status(self, phase: int) -> SubsystemStatus | None:
        """Get status of a specific phase subsystem."""
        return self._subsystems.get(phase)

    def summary(self) -> str:
        """Human-readable kernel summary."""
        healthy = sum(
            1 for s in self._subsystems.values() if s.health == SubsystemHealth.HEALTHY
        )
        failed = sum(
            1 for s in self._subsystems.values() if s.health == SubsystemHealth.FAILED
        )
        return (
            f"🏭 Autonomous Enterprise Kernel\n"
            f"  Status: {self._status.value}\n"
            f"  Uptime: {self.uptime:.0f}s\n"
            f"  Cycles: {self._cycle_count}\n"
            f"  Phases: {healthy}/{len(self._subsystems)} healthy, "
            f"{failed} failed\n"
            f"  Revenue: R$ {self._total_revenue:.2f}\n"
            f"  Alerts: {len(self._alerts)}"
        )


