# ── Core Kernel ────────────────────────────────────────────────


class AutonomousEnterpriseKernel:
    """AG-Kit Phase 20: The complete self-sustaining kernel.

    Singleton. Initializes all 19 phases, provides lifecycle management,
    health monitoring, and the integration feedback loop.

    Usage:
        kernel = AutonomousEnterpriseKernel.get_instance()
        kernel.boot()
        kernel.run_cycle()
        status = kernel.health_check()
        kernel.shutdown()
    """

    _instance: AutonomousEnterpriseKernel | None = None
    _lock = threading.Lock()

    def __init__(self):
        self._init_lock = threading.Lock()
        self._status: KernelStatus = KernelStatus.BOOTING
        self._start_time: float = 0.0
        self._cycle_count: int = 0
        self._subsystems: dict[int, SubsystemStatus] = {}
        self._alerts: list[KernelAlert] = []
        self._modules: dict[int, Any] = {}  # cached module references
        self._total_revenue: float = 0.0

        # Integration hooks (set by OrchestratorV2 or externally)
        self._orchestrator: Any = None
        self._world_model: Any = None
        self._constraint_graph: Any = None
        self._economic_engine: Any = None
        self._digital_twin: Any = None
        self._self_improvement: Any = None
        self._organization: Any = None
        self._cognitive_mesh: Any = None

        # Initialize subsystem registry
        for phase, name, module_path in PHASES_1_19:
            self._subsystems[phase] = SubsystemStatus(
                phase=phase, name=name, module_path=module_path
            )

    # ── Singleton ───────────────────────────────────────────

    @classmethod
    def get_instance(cls) -> AutonomousEnterpriseKernel:
        """Get the singleton kernel instance."""
        if cls._instance is None:
            with cls._lock:
                if cls._instance is None:
                    cls._instance = cls()
        return cls._instance

    @classmethod
    def reset_instance(cls) -> None:
        """Reset the singleton (useful for testing)."""
        with cls._lock:
            cls._instance = None

    # ── Properties ──────────────────────────────────────────

    @property
    def status(self) -> KernelStatus:
        return self._status

    @property
    def uptime(self) -> float:
        if self._start_time <= 0:
            return 0.0
        return time.time() - self._start_time

    @property
    def cycle_count(self) -> int:
        return self._cycle_count

    @property
    def alerts(self) -> list[KernelAlert]:
        return list(self._alerts)

    # ── Lifecycle ───────────────────────────────────────────

    def boot(self, orchestrator: Any = None) -> KernelSnapshot:
        """Initialize all subsystems and start the kernel.

        Each subsystem is probed via importlib — failures are recorded
        but do not prevent the kernel from booting (graceful degradation).
        """
        self._start_time = time.time()
        self._orchestrator = orchestrator

        import importlib
        import sys

        for phase, name, module_path in PHASES_1_19:
            sub = self._subsystems[phase]
            try:
                # Try to import the module (lazy probe)
                if module_path not in sys.modules:
                    importlib.import_module(module_path)
                sub.health = SubsystemHealth.HEALTHY
                sub.last_heartbeat = time.time()
                sub.uptime = time.time() - self._start_time
            except ImportError as e:
                sub.health = SubsystemHealth.FAILED
                sub.error = str(e)
                self._emit_alert(
                    AlertSeverity.WARNING,
                    f"Phase {phase} ({name})",
                    f"Module not available: {e}",
                )
            except Exception as e:
                sub.health = SubsystemHealth.FAILED
                sub.error = str(e)
                self._emit_alert(
                    AlertSeverity.WARNING,
                    f"Phase {phase} ({name})",
                    f"Failed to initialize: {e}",
                )

        # Determine overall status
        failed = sum(
            1 for s in self._subsystems.values() if s.health == SubsystemHealth.FAILED
        )
        degraded = sum(
            1 for s in self._subsystems.values() if s.health == SubsystemHealth.DEGRADED
        )
        total = len(self._subsystems)

        if failed == total:
            self._status = KernelStatus.ERROR
        elif failed > 0 or degraded > 0:
            self._status = KernelStatus.DEGRADED
        else:
            self._status = KernelStatus.RUNNING

        self._emit_alert(
            AlertSeverity.INFO,
            "Kernel",
            f"Booted: {total - failed - degraded}/{total} healthy, "
            f"{degraded} degraded, {failed} failed",
        )

        return self.snapshot()

    def shutdown(self) -> KernelSnapshot:
        """Gracefully shut down all subsystems."""
        self._status = KernelStatus.SHUTDOWN
        self._emit_alert(AlertSeverity.INFO, "Kernel", "Shutdown complete")
        return self.snapshot()

    def run_cycle(self, context: dict[str, Any] | None = None) -> dict[str, Any]:
        """Execute one full cycle of the autonomous kernel.

        The cycle connects all 19 phases into a feedback loop:
          1. World Model predicts environment state
          2. Constraint Intelligence checks reality constraints
          3. Economic Intelligence allocates resources
          4. Agent Evolution mutates/selects agents
          5. Cognitive Mesh shares knowledge across agents
          6. Digital Twin simulates the plan
          7. Self-Improvement diagnoses and patches
          8. Organization records the cycle

        Returns a dict with cycle results.
        """
        self._cycle_count += 1
        cycle_id = str(uuid.uuid4())[:8]
        results: dict[str, Any] = {
            "cycle_id": cycle_id,
            "cycle_number": self._cycle_count,
            "timestamp": time.time(),
            "phases": {},
        }

        # Step 1: World Model → predict environment state
        if self._world_model is not None:
            try:
                pred = self._world_model.predict()
                results["phases"]["world_model"] = {
                    "status": "ok",
                    "prediction": str(pred)[:200],
                }
                self._subsystems[12].health = SubsystemHealth.HEALTHY
            except Exception as e:
                results["phases"]["world_model"] = {"status": "error", "error": str(e)}
                self._subsystems[12].health = SubsystemHealth.DEGRADED
        else:
            results["phases"]["world_model"] = {"status": "skipped"}
            self._subsystems[12].last_heartbeat = time.time()

        # Step 2: Constraint → check constraints
        if self._constraint_graph is not None:
            try:
                cstatus = self._constraint_graph.check_all()
                results["phases"]["constraint"] = {
                    "status": "ok",
                    "violations": len(cstatus.get("violations", [])),
                }
                self._subsystems[11].health = SubsystemHealth.HEALTHY
            except Exception as e:
                results["phases"]["constraint"] = {"status": "error", "error": str(e)}
                self._subsystems[11].health = SubsystemHealth.DEGRADED
        else:
            results["phases"]["constraint"] = {"status": "skipped"}
            self._subsystems[11].last_heartbeat = time.time()

        # Step 3: Economic → allocate resources
        if self._economic_engine is not None:
            try:
                alloc = self._economic_engine.allocate()
                results["phases"]["economic"] = {
                    "status": "ok",
                    "allocation": str(alloc)[:200],
                }
                self._subsystems[13].health = SubsystemHealth.HEALTHY
            except Exception as e:
                results["phases"]["economic"] = {"status": "error", "error": str(e)}
                self._subsystems[13].health = SubsystemHealth.DEGRADED
        else:
            results["phases"]["economic"] = {"status": "skipped"}
            self._subsystems[13].last_heartbeat = time.time()

        # Step 4: Digital Twin → simulate
        if self._digital_twin is not None:
            try:
                sim = self._digital_twin.simulate({"cycle": cycle_id})
                results["phases"]["digital_twin"] = {
                    "status": "ok",
                    "simulation": str(sim)[:200],
                }
                self._subsystems[16].health = SubsystemHealth.HEALTHY
            except Exception as e:
                results["phases"]["digital_twin"] = {"status": "error", "error": str(e)}
                self._subsystems[16].health = SubsystemHealth.DEGRADED
        else:
            results["phases"]["digital_twin"] = {"status": "skipped"}
            self._subsystems[16].last_heartbeat = time.time()

        # Step 5: Self-Improvement → diagnose and patch
        if self._self_improvement is not None:
            try:
                diag = self._self_improvement.run_cycle(
                    constraint_graph=self._constraint_graph,
                    economic=self._economic_engine,
                )
                findings_count = len(diag.get("findings", []))
                patches_count = len(diag.get("patches", []))
                results["phases"]["self_improvement"] = {
                    "status": "ok",
                    "findings": findings_count,
                    "patches": patches_count,
                }
                if patches_count > 0:
                    self._emit_alert(
                        AlertSeverity.INFO,
                        "Self-Improvement",
                        f"Generated {patches_count} patches",
                    )
                self._subsystems[17].health = SubsystemHealth.HEALTHY
            except Exception as e:
                results["phases"]["self_improvement"] = {
                    "status": "error",
                    "error": str(e),
                }
                self._subsystems[17].health = SubsystemHealth.DEGRADED
        else:
            results["phases"]["self_improvement"] = {"status": "skipped"}
            self._subsystems[17].last_heartbeat = time.time()

        # Step 6: Organization → record cycle
        if self._organization is not None:
            try:
                org_result = self._organization.run_cycle(cycle_id)
                results["phases"]["organization"] = {
                    "status": "ok",
                    "result": str(org_result)[:200],
                }
                self._subsystems[19].health = SubsystemHealth.HEALTHY
            except Exception as e:
                results["phases"]["organization"] = {"status": "error", "error": str(e)}
                self._subsystems[19].health = SubsystemHealth.DEGRADED
        else:
            results["phases"]["organization"] = {"status": "skipped"}
            self._subsystems[19].last_heartbeat = time.time()

        # Update heartbeats for all healthy subsystems
        now = time.time()
        for sub in self._subsystems.values():
            if sub.health in (SubsystemHealth.HEALTHY, SubsystemHealth.DEGRADED):
                sub.last_heartbeat = now
                sub.uptime = now - self._start_time

        results["status"] = self._status.value
        results["subsystems_healthy"] = sum(
            1 for s in self._subsystems.values() if s.health == SubsystemHealth.HEALTHY
        )
        results["subsystems_total"] = len(self._subsystems)

        return results

    # ── Health & Monitoring ─────────────────────────────────

    def health_check(self) -> dict[str, Any]:
        """Comprehensive health check across all subsystems."""
        now = time.time()
        healthy = 0
        degraded = 0
        failed = 0
        subsystem_details = []

        for phase in sorted(self._subsystems.keys()):
            sub = self._subsystems[phase]
            status = sub.health.value
            time_since_hb = now - sub.last_heartbeat if sub.last_heartbeat > 0 else -1

            entry = {
                "phase": phase,
                "name": sub.name,
                "status": status,
                "uptime_seconds": round(sub.uptime, 1),
                "seconds_since_heartbeat": round(time_since_hb, 1)
                if time_since_hb >= 0
                else "never",
                "error": sub.error,
                "metrics": sub.metrics,
            }
            subsystem_details.append(entry)

            if sub.health == SubsystemHealth.HEALTHY:
                healthy += 1
            elif sub.health == SubsystemHealth.DEGRADED:
                degraded += 1
            elif sub.health == SubsystemHealth.FAILED:
                failed += 1

        return {
            "kernel_status": self._status.value,
            "uptime_seconds": round(self.uptime, 1),
            "cycle_count": self._cycle_count,
            "subsystems": {
                "total": len(self._subsystems),
                "healthy": healthy,
                "degraded": degraded,
                "failed": failed,
            },
            "alerts_active": len([a for a in self._alerts if not a.acknowledged]),
            "alerts_total": len(self._alerts),
            "subsystem_details": subsystem_details,
            "total_revenue": round(self._total_revenue, 2),
            "timestamp": now,
        }

    def snapshot(self) -> KernelSnapshot:
        """Generate a complete kernel snapshot (for digital twin)."""
        return KernelSnapshot(
            status=self._status,
            subsystems=list(self._subsystems.values()),
            alerts=self._alerts[-20:],  # last 20 alerts
            uptime=self.uptime,
            cycle_count=self._cycle_count,
            total_revenue=self._total_revenue,
            active_agents=len(
                [
                    s
                    for s in self._subsystems.values()
                    if s.health == SubsystemHealth.HEALTHY
                ]
            ),
            total_workflows=len(self._subsystems),
            timestamp=time.time(),
        )

