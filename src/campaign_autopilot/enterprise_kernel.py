from __future__ import annotations

import json
import threading
import time
import uuid
from dataclasses import dataclass, field, asdict
from enum import Enum
from typing import Any


# ── Types ─────────────────────────────────────────────────────


class KernelStatus(Enum):
    BOOTING = "booting"
    RUNNING = "running"
    DEGRADED = "degraded"  # some subsystems failed
    ERROR = "error"
    SHUTDOWN = "shutdown"


class SubsystemHealth(Enum):
    HEALTHY = "healthy"
    DEGRADED = "degraded"
    FAILED = "failed"
    NOT_INITIALIZED = "not_initialized"


class AlertSeverity(Enum):
    INFO = "info"
    WARNING = "warning"
    CRITICAL = "critical"
    FATAL = "fatal"


# ── Domain Models ─────────────────────────────────────────────


@dataclass
class SubsystemStatus:
    """Status of a single subsystem (phase module)."""

    phase: int
    name: str
    health: SubsystemHealth = SubsystemHealth.NOT_INITIALIZED
    module_path: str = ""
    error: str | None = None
    last_heartbeat: float = 0.0
    uptime: float = 0.0
    metrics: dict[str, float] = field(default_factory=dict)


@dataclass
class KernelAlert:
    """An alert generated by the health monitor."""

    alert_id: str = ""
    severity: AlertSeverity = AlertSeverity.INFO
    source: str = ""
    message: str = ""
    timestamp: float = 0.0
    acknowledged: bool = False
    context: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self):
        if not self.alert_id:
            self.alert_id = str(uuid.uuid4())[:8]
        if not self.timestamp:
            self.timestamp = time.time()


@dataclass
class KernelSnapshot:
    """Complete state snapshot for digital twin / observability."""

    status: KernelStatus = KernelStatus.BOOTING
    subsystems: list[SubsystemStatus] = field(default_factory=list)
    alerts: list[KernelAlert] = field(default_factory=list)
    uptime: float = 0.0
    cycle_count: int = 0
    total_revenue: float = 0.0
    active_agents: int = 0
    total_workflows: int = 0
    kernel_version: str = "5.2.1"
    phase_20_version: str = "1.0.0"
    timestamp: float = 0.0

    def __post_init__(self):
        if not self.timestamp:
            self.timestamp = time.time()

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), indent=2, default=str)


